/**
 * Chat message rendering (markdown bubbles, collapsible tool cards) and the
 * extension-host -> webview protocol dispatch.
 *
 * Concatenated after script.ts and markdown.ts by html.ts; references their
 * variables (input, messages, savedState, ...) and mdRender(). All top-level
 * statements here run after the shell's, which is the only ordering
 * requirement.
 *
 * Pure string builder — no vscode dependency, unit-testable.
 * NOTE: no template literals (see Handoff-Summary.md lessons learned).
 */

export function buildMessagesScript(): string {
    return [
        "var lastAssistantMessageDiv = null;",
        "var allAssistantMessages = [];",
        "",
        "function setMessageToolsExpanded(msgDiv, expanded) {",
        "    if (!msgDiv) { return; }",
        "    var tools = msgDiv.__tools || [];",
        "    for (var i = 0; i < tools.length; i++) {",
        "        var t = tools[i];",
        "        if (t && t.card) { t.card.style.display = expanded ? '' : 'none'; }",
        "    }",
        "    msgDiv.__toolsExpanded = expanded;",
        "    if (msgDiv.__icon) { msgDiv.__icon.textContent = expanded ? '▾' : '▸'; }",
        "}",
        "",
        "function addToolMessage(text) {",
        "    if (!lastAssistantMessageDiv) { return; }",
        "    var name = 'tool';",
        "    var body = String(text == null ? '' : text);",
        "    var sep = body.indexOf(' → ');",
        "    if (sep > 0) {",
        "        name = body.substring(0, sep);",
        "        body = body.substring(sep + 3);",
        "    }",
        "    var card = document.createElement('div');",
        "    card.className = 'msg tool';",
        "    var head = document.createElement('div');",
        "    head.className = 'tool-head';",
        "    var chev = document.createElement('span');",
        "    chev.className = 'chev';",
        "    chev.textContent = '▸';",
        "    var nameEl = document.createElement('span');",
        "    nameEl.className = 'tool-name';",
        "    nameEl.textContent = name;",
        "    var preview = document.createElement('span');",
        "    preview.className = 'tool-preview';",
        "    var firstLine = (body.split('\\n')[0] || '').trim();",
        "    if (firstLine.length > 120) { firstLine = firstLine.substring(0, 120) + '…'; }",
        "    preview.textContent = firstLine;",
        "    var status = document.createElement('span');",
        "    status.className = 'tool-status';",
        "    status.textContent = '✓';",
        "    head.appendChild(chev);",
        "    head.appendChild(nameEl);",
        "    head.appendChild(preview);",
        "    head.appendChild(status);",
        "    var bodyEl = document.createElement('div');",
        "    bodyEl.className = 'tool-body';",
        "    var pre = document.createElement('pre');",
        "    pre.textContent = body;",
        "    bodyEl.appendChild(pre);",
        "    bodyEl.style.display = 'none';",
        "    head.addEventListener('click', function (e) {",
        "        e.stopPropagation();",
        "        var open = bodyEl.style.display !== 'none';",
        "        bodyEl.style.display = open ? 'none' : 'block';",
        "        chev.textContent = open ? '▸' : '▾';",
        "        preview.style.display = open ? '' : 'none';",
        "    });",
        "    card.appendChild(head);",
        "    card.appendChild(bodyEl);",
        "",
        "    lastAssistantMessageDiv.appendChild(card);",
        "    if (!lastAssistantMessageDiv.__tools) { lastAssistantMessageDiv.__tools = []; }",
        "    lastAssistantMessageDiv.__tools.push({ card: card, head: head, body: bodyEl, chev: chev, preview: preview });",
        "    if (lastAssistantMessageDiv.__toolsExpanded === false) {",
        "        card.style.display = 'none';",
        "    }",
        "    messages.scrollTop = messages.scrollHeight;",
        "}",
        "",
        "function addMessage(role, text) {",
        "    if (role === 'tool') { addToolMessage(text); return; }",
        "    if (role === 'assistant' && !String(text == null ? '' : text).trim()) { return; }",
        "",
        "    var div = document.createElement('div');",
        "    div.className = 'msg ' + role;",
        "    if (role === 'assistant') {",
        "        div.__tools = [];",
        "        div.__toolsExpanded = true;",
        "        if (lastAssistantMessageDiv) {",
        "            setMessageToolsExpanded(lastAssistantMessageDiv, false);",
        "        }",
        "        var icon = document.createElement('div');",
        "        icon.className = 'my-theme-icon';",
        "        icon.textContent = '▾';",
        "        icon.style.cssFloat = 'left';",
        "        icon.style.marginRight = '8px';",
        "        icon.style.cursor = 'pointer';",
        "        icon.style.userSelect = 'none';",
        "        icon.style.fontSize = '18px';",
        "        icon.title = 'Toggle tool calls';",
        "        icon.addEventListener('click', function () {",
        "            setMessageToolsExpanded(div, !div.__toolsExpanded);",
        "        });",
        "        div.__icon = icon;",
        "        div.appendChild(icon);",
        "        var md = document.createElement('div');",
        "        md.className = 'md';",
        "        md.innerHTML = mdRender(text);",
        "        div.appendChild(md);",
        "        lastAssistantMessageDiv = div;",
        "        allAssistantMessages.push(div);",
        "    } else if (role === 'user') {",
        "        div.style.display = 'flex';",
        "        div.style.alignItems = 'center';",
        "        div.style.gap = '8px';",
        "        var promptIcon = document.createElement('span');",
        "        promptIcon.textContent = '▾';",
        "        promptIcon.style.cursor = 'pointer';",
        "        promptIcon.style.userSelect = 'none';",
        "        promptIcon.style.fontSize = '24px';",
        "        promptIcon.style.lineHeight = '1.2';",
        "        promptIcon.style.flexShrink = '0';",
        "        var pre = document.createElement('pre');",
        "        pre.textContent = String(text == null ? '' : text);",
        "        pre.style.margin = '0';",
        "        pre.style.fontSize = '14px';",
        "        pre.style.lineHeight = '1.5';",
        "        div.appendChild(promptIcon);",
        "        div.appendChild(pre);",
        "        div.style.cursor = 'pointer';",
        "        div.__promptExpanded = true;",
        "        div.addEventListener('click', function () {",
        "            var expanded = !div.__promptExpanded;",
        "            div.__promptExpanded = expanded;",
        "            promptIcon.textContent = expanded ? '▾' : '▸';",
        "            var elem = div.nextElementSibling;",
        "            while (elem && elem.className && elem.className.indexOf('msg assistant') >= 0) {",
        "                elem.style.display = expanded ? '' : 'none';",
        "                elem = elem.nextElementSibling;",
        "            }",
        "        });",
        "    } else {",
        "        var pre = document.createElement('pre');",
        "        pre.textContent = String(text == null ? '' : text);",
        "        div.appendChild(pre);",
        "    }",
        "    messages.appendChild(div);",
        "    messages.scrollTop = messages.scrollHeight;",
        "}",
        "function renderQuickPickCard(callId, placeHolder, options) {",
        "    if (!messages) { return; }",
        "    var card = document.createElement('div');",
        "    card.className = 'chat-prompt-card';",
        "    card.id = 'prompt_' + callId;",
        "    ",
        "    var title = document.createElement('div');",
        "    title.className = 'chat-prompt-title';",
        "    title.textContent = placeHolder;",
        "    card.appendChild(title);",
        "    ",
        "    var list = document.createElement('div');",
        "    list.className = 'chat-qp-list';",
        "    options.forEach(function(opt) {",
        "        var btn = document.createElement('button');",
        "        btn.className = 'chat-qp-option';",
        "        btn.textContent = opt;",
        "        btn.addEventListener('click', function() {",
        "            vscode.postMessage({ type: 'quickPickSelected', callId: callId, value: opt });",
        "            card.remove();",
        "        });",
        "        list.appendChild(btn);",
        "    });",
        "    card.appendChild(list);",
        "    messages.appendChild(card);",
        "    messages.scrollTop = messages.scrollHeight;",
        "}",        
        "function renderInputBoxCard(callId, promptText, placeHolder) {",
        "    if (!messages) { return; }",
        "    var card = document.createElement('div');",
        "    card.className = 'chat-prompt-card';",
        "    card.id = 'prompt_' + callId;",
        "    ",
        "    var title = document.createElement('div');",
        "    title.className = 'chat-prompt-title';",
        "    title.textContent = promptText;",
        "    card.appendChild(title);",
        "    ",
        "    var row = document.createElement('div');",
        "    row.className = 'chat-ib-row';",
        "    ",
        "    var inputEl = document.createElement('input');",
        "    inputEl.type = 'text';",
        "    inputEl.className = 'chat-ib-input';",
        "    inputEl.placeholder = placeHolder || '';",
        "    ",
        "    var submitBtn = document.createElement('button');",
        "    submitBtn.className = 'chat-ib-btn';",
        "    submitBtn.textContent = 'Submit';",
        "    ",
        "    function submit() {",
        "        var val = inputEl.value;",
        "        vscode.postMessage({ type: 'inputBoxSubmitted', callId: callId, value: val });",
        "        card.remove();",
        "    }",
        "    ",
        "    submitBtn.addEventListener('click', submit);",
        "    inputEl.addEventListener('keydown', function(e) {",
        "        if (e.key === 'Enter') { e.preventDefault(); submit(); }",
        "    });",
        "    ",
        "    row.appendChild(inputEl);",
        "    row.appendChild(submitBtn);",
        "    card.appendChild(row);",
        "    messages.appendChild(card);",
        "    messages.scrollTop = messages.scrollHeight;",
        "    try { inputEl.focus(); } catch (e) {}",
        "}",
        // ---- Extension-host -> webview protocol ----
        "window.addEventListener('message', function (event) {",
        "    var msg = event.data;",
        "    logLine('recv: ' + JSON.stringify(msg).substring(0, 120));",
        "    if (!msg || !msg.type) { return; }",
        "    switch (msg.type) {",
        "        case 'showSetup':",
        "            if (setupMaxSteps) setupMaxSteps.value = String(msg.maxSteps || 15);",
        "            if (setupAuthType) setupAuthType.value = msg.authType === 'env' ? 'env' : 'key';",
        "            updateSetupAuthInput(msg.authType, msg.authValue, Boolean(msg.apiKeyStored));",
        "            if (setupOverlay) setupOverlay.style.display = 'flex';",
        "            break;",
        "        case 'hideSetup':",
        "            if (setupOverlay) setupOverlay.style.display = 'none';",
        "            break;",
        "        case 'setupModelsList':",
        "            if (setupModelSelect) {",
        "                setupModelSelect.innerHTML = '';",
        "                msg.models.forEach(function(m) {",
        "                    var opt = document.createElement('option');",
        "                    opt.value = m;",
        "                    opt.textContent = m;",
        "                    setupModelSelect.appendChild(opt);",
        "                });",
        "            }",
        "            if (setupStatus) { setupStatus.textContent = 'Success! Pick a model.'; setupStatus.style.color = '#104a10'; }",
        "            if (setupSaveBtn) setupSaveBtn.disabled = false;",
        "            break;",
        "        case 'setupError':",
        "            if (setupStatus) { setupStatus.textContent = 'Error: ' + msg.text; setupStatus.style.color = 'var(--vscode-errorForeground)'; }",
        "            break;",
        "        case 'modelsList':",
        "            updateModelOptions(msg.models, msg.selected);",
        "            if (msg.error) { setStatus('failed fetching models', 'st-err'); }",
        "            else if (agentRunning) { setStatus('agent running...', 'st-wait'); }",
        "            else { setStatus('ready', 'st-ok'); }",
        "            break;",
        "        case 'modelTiming':",
        "            timings[msg.model] = (typeof msg.ms === 'number') ? msg.ms : -1;",
        "            renderModelOptions();",
        "            break;",
        "        case 'benchmarkDone':",
        "            if (timeModels) { timeModels.disabled = false; }",
        "            setStatus('timing complete', 'st-ok');",
        "            break;",
        "        case 'delta':",
        "            addMessage('assistant', msg.text);",
        "            setStatus('streaming...', 'st-wait');",
        "            break;",
        "        case 'done':",
        "            agentRunning = false;",
        "            send.disabled = false;",
        "            if (stop) { stop.disabled = true; }",
        "            if (compactBtn) { compactBtn.disabled = false; }",
        "            setStatus('ready', 'st-ok');",
        "            if (allAssistantMessages.length > 1) {",
        "                for (var i = 0; i < allAssistantMessages.length - 1; i++) {",
        "                    setMessageToolsExpanded(allAssistantMessages[i], false);",
        "                }",
        "            }",
        "            var lastUserMsg = null;",
        "            for (var j = messages.children.length - 1; j >= 0; j--) {",
        "                if (messages.children[j].className && messages.children[j].className.indexOf('msg user') >= 0) {",
        "                    lastUserMsg = messages.children[j];",
        "                    break;",
        "                }",
        "            }",
        "            if (lastUserMsg) {",
        "                setTimeout(function() { lastUserMsg.scrollIntoView({ behavior: 'smooth', block: 'start' }); }, 0);",
        "            }",
        "            break;",
        "        case 'clearChat':",
        "            // Host reset the conversation + session; drop the rendered bubbles.",
        "            if (messages) { messages.innerHTML = ''; }",
        "            allAssistantMessages = [];",
        "            lastAssistantMessageDiv = null;",
        "            agentRunning = false;",
        "            send.disabled = false;",
        "            if (stop) { stop.disabled = true; }",
        "            if (compactBtn) { compactBtn.disabled = false; }",
        "            setStatus('chat cleared', 'st-ok');",
        "            break;",
        "        case 'error':",
        "            agentRunning = false;",
        "            addMessage('error', msg.text || 'An error occurred.');",
        "            send.disabled = false;",
        "            if (stop) { stop.disabled = true; }",
        "            if (compactBtn) { compactBtn.disabled = false; }",
        "            setStatus('error', 'st-err');",
        "            break;",
        "        case 'tool':",
        "            addMessage('tool', msg.text || '');",
        "            break;",
        "        case 'renderHistory':",
        "            (msg.items || []).forEach(function (it) { addMessage(it.role, it.text); });",
        "            if (savedState && messages) {",
        "                if (savedState.atBottom === false && typeof savedState.scrollTop === 'number') {",
        "                    messages.scrollTop = savedState.scrollTop;",
        "                } else {",
        "                    messages.scrollTop = messages.scrollHeight;",
        "                }",
        "            }",
        "            break;",
        "        case 'runState':",
        "            agentRunning = Boolean(msg.running);",
        "            if (agentRunning) {",
        "                send.disabled = true;",
        "                if (stop) { stop.disabled = false; }",
        "                if (compactBtn) { compactBtn.disabled = true; }",
        "                setStatus('agent running...', 'st-wait');",
        "            }",
        "            break;",
        "        case 'promptState':",
        "            promptHistory = Array.isArray(msg.history) ? msg.history.slice() : [];",
        "            historyIndex = promptHistory.length;",
        "            pendingDraft = '';",
        "            if (input && !input.value && typeof msg.draft === 'string' && msg.draft) {",
        "                input.value = msg.draft;",
        "                saveViewState();",
        "            }",
        "            if (!heightApplied && input && typeof msg.inputHeight === 'number' && msg.inputHeight >= 48) {",
        "                input.style.height = msg.inputHeight + 'px';",
        "                heightApplied = true;",
        "            }",
        "            break;",
        "        case 'promptHistory':",
        "            promptHistory = Array.isArray(msg.items) ? msg.items.slice() : [];",
        "            historyIndex = promptHistory.length;",
        "            pendingDraft = '';",
        "            break;",
        "        case 'openFilesList':",
        "            renderAttachMenu(msg.files);",
        "            break;",
        "        case 'insertFileMention':",
        "            insertFileRef(msg.path);",
        "            break;",
        "        case 'showQuickPickCard':",
        "            renderQuickPickCard(msg.callId, msg.placeHolder, msg.options);",
        "            break;",
        "        case 'showInputBoxCard':",
        "            renderInputBoxCard(msg.callId, msg.prompt, msg.placeHolder);",
        "            break;",
        "        default:",
        "            logLine('unknown msg.type: ' + msg.type);",
        "    }",
        "});",
        "logLine('webview scripts loaded');",
    ].join("\n");
}